"""Scaffold dated course entries and regenerate the work-log indexes.

Usage (from the repo root):
    uv run tools/worklog.py new circuits in-class "Thevenin equivalents" --tags nodal,thevenin
    uv run tools/worklog.py new biofluid-mechanics computation "Poiseuille flow in a stenosis"
    uv run tools/worklog.py build           # regenerate LOG.md and per-course indexes
    uv run tools/worklog.py build --check   # exit 1 if the indexes are stale (used in CI)

Layout produced:
    <course>/in-class/YYYY-MM-DD-<slug>/{README.md, main.py}
    <course>/computations/YYYY-MM-DD-<slug>/{README.md, main.py}
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REGISTRY = Path(__file__).resolve().parent / "courses.toml"

KIND_DIRS = {"in-class": "in-class", "computation": "computations"}
KIND_LABELS = {"in-class": "In-class", "computation": "Computation"}
KIND_ALIASES = {"in-class": "in-class", "inclass": "in-class", "class": "in-class",
                "computation": "computation", "computations": "computation", "comp": "computation"}

ENTRY_DIR_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-([a-z0-9][a-z0-9-]*)$")
GENERATED_NOTE = "<!-- Generated by tools/worklog.py. Edit entry READMEs, then run `uv run tools/worklog.py build`. -->"


@dataclass(frozen=True)
class Course:
    slug: str
    name: str


@dataclass
class Entry:
    course: Course
    kind: str
    path: Path
    date: dt.date
    title: str
    tags: list[str] = field(default_factory=list)
    summary: str = ""


def load_courses(registry: Path = REGISTRY) -> dict[str, Course]:
    data = tomllib.loads(registry.read_text(encoding="utf-8"))
    return {c["slug"]: Course(c["slug"], c["name"]) for c in data["course"]}


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    if not slug:
        raise ValueError(f"cannot build a folder name from title {text!r}")
    return slug[:60].rstrip("-")


def parse_front_matter(text: str) -> tuple[dict[str, str | list[str]], str]:
    """Parse the minimal `key: value` / `key: [a, b]` front matter used by entry READMEs."""
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    meta: dict[str, str | list[str]] = {}
    for line in text[3:end].strip().splitlines():
        key, sep, value = line.partition(":")
        if not sep:
            continue
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            meta[key.strip()] = [v.strip().strip("'\"") for v in value[1:-1].split(",") if v.strip()]
        else:
            meta[key.strip()] = value.strip("'\"")
    return meta, text[end + 4 :].lstrip("\n")


def first_paragraph_under(body: str, heading: str) -> str:
    match = re.search(rf"^##\s+{re.escape(heading)}\s*$\n+(.+?)(?:\n\s*\n|\n##|\Z)", body, re.M | re.S)
    if not match:
        return ""
    text = " ".join(match.group(1).split())
    return "" if text.startswith("<!--") else text


def read_entry(course: Course, kind: str, path: Path) -> Entry | None:
    m = ENTRY_DIR_RE.match(path.name)
    if not m:
        return None
    readme = path / "README.md"
    meta: dict[str, str | list[str]] = {}
    body = ""
    if readme.exists():
        meta, body = parse_front_matter(readme.read_text(encoding="utf-8"))
    title = meta.get("title") or m.group(2).replace("-", " ").capitalize()
    tags = meta.get("tags") or []
    return Entry(
        course=course,
        kind=kind,
        path=path,
        date=dt.date.fromisoformat(m.group(1)),
        title=str(title),
        tags=list(tags) if isinstance(tags, list) else [str(tags)],
        summary=first_paragraph_under(body, "Problem"),
    )


def collect_entries(root: Path, courses: dict[str, Course]) -> tuple[list[Entry], list[Path]]:
    entries: list[Entry] = []
    skipped: list[Path] = []
    for course in courses.values():
        for kind, dirname in KIND_DIRS.items():
            kind_dir = root / course.slug / dirname
            if not kind_dir.is_dir():
                continue
            for child in sorted(p for p in kind_dir.iterdir() if p.is_dir()):
                entry = read_entry(course, kind, child)
                if entry is None:
                    skipped.append(child)
                else:
                    entries.append(entry)
    entries.sort(key=lambda e: (e.date, e.course.slug, e.path.name), reverse=True)
    return entries, skipped


def _rel(path: Path, start: Path) -> str:
    return path.relative_to(start).as_posix()


def _tags(entry: Entry) -> str:
    return " ".join(f"`{t}`" for t in entry.tags)


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render_root_log(root: Path, entries: list[Entry], courses: dict[str, Course]) -> str:
    lines = [GENERATED_NOTE, "", "# Work Log", ""]
    lines.append("Chronological record of in-class work and computations across courses, newest first.")
    lines.append("")
    counts = []
    for course in courses.values():
        n = sum(e.course == course for e in entries)
        if n:
            counts.append(f"[{course.name}]({course.slug}/) ({n})")
    if counts:
        lines += ["**Courses:** " + " · ".join(counts), ""]
    if not entries:
        lines += ["_No entries yet. Create one with `uv run tools/worklog.py new <course> in-class \"<title>\"`._", ""]
        return "\n".join(lines)
    current_month = None
    for e in entries:
        month = e.date.strftime("%B %Y")
        if month != current_month:
            if current_month is not None:
                lines.append("")
            lines += [f"## {month}", "", "| Date | Course | Type | Entry | Tags |", "| --- | --- | --- | --- | --- |"]
            current_month = month
        lines.append(
            f"| {e.date.isoformat()} | {e.course.name} | {KIND_LABELS[e.kind]} "
            f"| [{_cell(e.title)}]({_rel(e.path, root)}/) | {_tags(e)} |"
        )
    lines.append("")
    return "\n".join(lines)


def render_kind_index(course: Course, kind: str, entries: list[Entry], kind_dir: Path) -> str:
    label = "In-Class Work" if kind == "in-class" else "Computations"
    blurb = (
        "Work done during lecture or lab: worked examples, derivations, and quick models."
        if kind == "in-class"
        else "Homework problems, computational assignments, and self-directed models."
    )
    lines = [GENERATED_NOTE, "", f"# {course.name}: {label}", "", blurb, ""]
    mine = [e for e in entries if e.course == course and e.kind == kind]
    if not mine:
        lines += [
            "_No entries yet._ Create one from the repo root:",
            "",
            "```bash",
            f'uv run tools/worklog.py new {course.slug} {kind} "<title>"',
            "```",
            "",
        ]
        return "\n".join(lines)
    lines += ["| Date | Entry | Summary | Tags |", "| --- | --- | --- | --- |"]
    for e in mine:
        summary = e.summary if len(e.summary) <= 140 else e.summary[:137].rstrip() + "..."
        lines.append(
            f"| {e.date.isoformat()} | [{_cell(e.title)}]({_rel(e.path, kind_dir)}/) | {_cell(summary)} | {_tags(e)} |"
        )
    lines.append("")
    return "\n".join(lines)


def generated_files(root: Path, courses: dict[str, Course]) -> tuple[dict[Path, str], list[Path]]:
    entries, skipped = collect_entries(root, courses)
    outputs = {root / "LOG.md": render_root_log(root, entries, courses)}
    for course in courses.values():
        course_dir = root / course.slug
        if not course_dir.is_dir():
            continue
        for kind, dirname in KIND_DIRS.items():
            kind_dir = course_dir / dirname
            if kind_dir.is_dir():
                outputs[kind_dir / "README.md"] = render_kind_index(course, kind, entries, kind_dir)
    return outputs, skipped


def _normalize(text: str) -> str:
    return text.replace("\r\n", "\n")


def build(root: Path, courses: dict[str, Course], check: bool = False) -> int:
    outputs, skipped = generated_files(root, courses)
    for path in skipped:
        print(f"warning: skipped {_rel(path, root)} (folder must be named YYYY-MM-DD-<slug>)", file=sys.stderr)
    stale = [p for p, text in outputs.items()
             if not p.exists() or _normalize(p.read_text(encoding="utf-8")) != text]
    if check:
        for p in stale:
            print(f"stale: {_rel(p, root)}", file=sys.stderr)
        if stale:
            print("Run `uv run tools/worklog.py build` and commit the result.", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.write_text(outputs[p], encoding="utf-8", newline="\n")
        print(f"wrote {_rel(p, root)}")
    if not stale:
        print("log is up to date")
    return 0


