def new_entry(root: Path, courses: dict[str, Course], course_slug: str, kind: str, title: str,
              date: dt.date, tags: list[str]) -> Path:
    if course_slug not in courses:
        raise ValueError(f"unknown course {course_slug!r}; choose from: {', '.join(courses)}")
    if kind not in KIND_DIRS:
        raise ValueError(f"unknown kind {kind!r}; use 'in-class' or 'computation'")
    course = courses[course_slug]
    entry_dir = root / course.slug / KIND_DIRS[kind] / f"{date.isoformat()}-{slugify(title)}"
    if entry_dir.exists():
        raise FileExistsError(f"{_rel(entry_dir, root)} already exists")
    entry_dir.mkdir(parents=True)
    fields = {
        "title": title.replace("\n", " ").strip(),
        "date": date.isoformat(),
        "course_slug": course.slug,
        "course_name": course.name,
        "kind": kind,
        "kind_label": KIND_LABELS[kind],
        "tags": ", ".join(slugify(t) for t in tags),
    }
    (entry_dir / "README.md").write_text(README_TEMPLATE.format(**fields), encoding="utf-8", newline="\n")
    (entry_dir / "main.py").write_text(MAIN_TEMPLATE.format(**fields), encoding="utf-8", newline="\n")
    return entry_dir


def main(argv: list[str] | None = None) -> int:
    courses = load_courses()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    p_new = sub.add_parser("new", help="scaffold a dated entry")
    p_new.add_argument("course", choices=sorted(courses))
    p_new.add_argument("kind", type=lambda s: KIND_ALIASES.get(s.lower(), s), choices=sorted(KIND_DIRS))
    p_new.add_argument("title")
    p_new.add_argument("--date", type=dt.date.fromisoformat, default=dt.date.today(), help="YYYY-MM-DD (default: today)")
    p_new.add_argument("--tags", default="", help="comma-separated, e.g. nodal,thevenin")

    p_build = sub.add_parser("build", help="regenerate LOG.md and per-course indexes")
    p_build.add_argument("--check", action="store_true", help="exit 1 if generated files are stale")

    args = parser.parse_args(argv)
    if args.command == "new":
        tags = [t for t in args.tags.split(",") if t.strip()]
        try:
            entry_dir = new_entry(REPO_ROOT, courses, args.course, args.kind, args.title, args.date, tags)
        except (ValueError, FileExistsError) as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 2
        print(f"created {_rel(entry_dir, REPO_ROOT)}/")
        return build(REPO_ROOT, courses)
    return build(REPO_ROOT, courses, check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
